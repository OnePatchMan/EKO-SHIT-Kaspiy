"""Create explicitly synthetic water and image fixtures for reproducible demos."""
from pathlib import Path
from datetime import datetime, timedelta, timezone
import json
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]


def main():
    destination = ROOT / 'examples'
    destination.mkdir(exist_ok=True)
    issued = datetime(2026, 5, 10, 9, tzinfo=timezone.utc)
    history = []
    for days_ago in range(13, -1, -1):
        history.append({'timestamp': (issued-timedelta(days=days_ago)).isoformat().replace('+00:00', 'Z'),
                        'temperature_c': round(17.0-days_ago*.35, 2),
                        'water_level_m': round(2.2-days_ago*.035, 3), 'inundated': True})
    request = {'station_id': 'delta-demo-01', 'species': 'cyprinus_carpio',
               'issued_at': issued.isoformat().replace('+00:00', 'Z'), 'horizon_hours': 72,
               'data_source': 'demo_synthetic', 'level_datum': 'synthetic local gauge zero', 'history': history}
    (destination / 'forecast_request.json').write_text(json.dumps(request, indent=2), encoding='utf-8')
    iot = {'station_id': request['station_id'], 'data_source': 'demo_synthetic',
           'level_datum': request['level_datum'], 'measurements': history}
    (destination / 'iot_batch.json').write_text(json.dumps(iot, indent=2), encoding='utf-8')
    images = ROOT / 'data' / 'images'
    images.mkdir(parents=True, exist_ok=True)
    before = Image.new('RGB', (512, 384), (142, 164, 110))
    draw = ImageDraw.Draw(before)
    draw.polygon([(0, 100), (150, 135), (320, 70), (512, 95), (512, 225), (320, 170), (150, 230), (0, 190)], fill=(48, 99, 124))
    before.save(images / 'synthetic_before.png')
    after = before.copy()
    ImageDraw.Draw(after).rectangle((240, 120, 280, 140), fill=(194, 167, 108))
    after.save(images / 'synthetic_after.png')
    (images / 'PROVENANCE.txt').write_text('Synthetic RGB test drawings generated by scripts/make_demo_data.py. Not satellite imagery, not a real spill or net. Pixel alignment is exact by construction.\n', encoding='utf-8')
    print('Created examples and synthetic images; all water records use data_source=demo_synthetic.')


if __name__ == '__main__':
    main()
